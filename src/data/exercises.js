// Safe lookup — returns a minimal placeholder rather than undefined so the
// UI never crashes if a programme references an id we haven't defined.
export function getExercise(id) {
  return (
    EXERCISES[id] || {
      id,
      name: id
        .split('_')
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join(' '),
      muscle_groups: [],
      tracking_type: 'weight_reps',
      is_calf_focus: false,
      cue: '',
      alternatives: {},
    }
  );
}
